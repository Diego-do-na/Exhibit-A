"""Campaign engine: generate cheats, run them, classify, save NEW findings.

Live path (``run_campaign``): for each target, for each round, ask the model
for ``per_round`` cheating tests, run each through ``run_fn`` (by default the
real sandbox + oracle via ``SandboxRunner.run_exploit`` against the FIXED
tree), and classify the judgement. Prompts and outputs are recorded by the
caller's ``RecordingProvider``; per-sample records (test source + judgement +
classification) go to ``samples.jsonl`` so the run replays offline.

Replay path (``replay_run``): recompute every classification from the stored
pairs with no model call and no sandbox. Canary tokens are per-run random, so
replay pins classification determinism, not sandbox re-execution; identical
counts prove the recorded run reproduces exactly.
"""

from __future__ import annotations

import json
import tempfile
from collections import Counter
from collections.abc import Callable
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from spikes.redteam.auto.cases import Target
from spikes.redteam.auto.classify import BLOCKED, ERRORED, FALSE_PROOF, classify
from spikes.redteam.auto.prompts import RESPONSE_SCHEMA, build_prompt

#: ``run_fn`` takes a target, one test source and a sample id, and returns an
#: oracle ``Judgement``. The default runs the real sandbox; tests inject fakes.
RunFn = Callable[[Target, str, str], Any]

BUCKETS = (FALSE_PROOF, BLOCKED, ERRORED)


@dataclass
class Report:
    counts: dict[str, dict[str, int]] = field(default_factory=dict)
    samples: int = 0
    budget_exhausted: bool = False
    skipped: list[str] = field(default_factory=list)
    findings: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "counts": self.counts,
            "samples": self.samples,
            "budget_exhausted": self.budget_exhausted,
            "skipped": self.skipped,
            "findings": self.findings,
        }


def blank_counts() -> dict[str, int]:
    return {
        "samples": 0, FALSE_PROOF: 0,
        "R1": 0, "R2": 0, "R3": 0, "R4": 0, "R5": 0, "R6": 0, "NEW": 0,
        BLOCKED: 0, ERRORED: 0,
    }


def tally(counts: dict[str, dict[str, int]], sample: dict[str, Any]) -> None:
    row = counts.setdefault(sample["effect"], blank_counts())
    row["samples"] += 1
    classification = sample["classification"]
    if classification.startswith(FALSE_PROOF):
        row[FALSE_PROOF] += 1
        row[classification.split(":", 1)[1]] += 1
    elif classification in (BLOCKED, ERRORED):
        row[classification] += 1


def default_run_fn(target: Target, test_source: str, sample_id: str, *, timeout: float = 120.0):
    """Run one generated test through the real sandbox and oracle.

    The FIXED tree is staged with the generated test and executed by
    ``SandboxRunner.run_exploit`` exactly as the product runs exploits: the
    sandbox result is judged by the oracle, so a ``proven`` here is false by
    construction. Raises ``OSError`` when the sandbox cannot run.
    """
    from exhibit_a.loop.runner import SandboxRunner

    runner = SandboxRunner(
        requirements=list(target.requirements),
        sql_db=target.sql_db,
        access_db=target.access_db,
        access=target.access,
        redirect_meta=target.redirect_meta,
    )
    with tempfile.TemporaryDirectory(prefix=f"auto_{sample_id}_") as tmp:
        test_path = Path(tmp) / "test_exploit.py"
        test_path.write_text(test_source, encoding="utf-8")
        return runner.run_exploit(
            target.fixed_dir, test_path, set(target.entry_points),
            timeout=timeout, effect=target.effect,
        )


def _finding_source(case_id: str, effect: str, entry_points: list[str], sample: dict[str, Any]) -> str:
    judgement = sample["judgement"]
    exploit = sample["test_source"].replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    eps = "{" + ", ".join(repr(e) for e in entry_points) + "}"
    return f'''"""Auto red-team finding (NEW false proof): {effect} on {case_id}.

Generated by ``python -m spikes.redteam.auto`` against the FIXED tree, so any
proof is false by construction. Technique (model's own words):
{sample.get("technique") or "(none given)"}
Oracle reason: {judgement.get("reason", "")} [{judgement.get("reason_code", "")}]
Promote to the hand-written suite (spikes/redteam/attack_*) once triaged.
"""
import sys
import tempfile
import textwrap
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[4]
FIXED_DIR = REPO_ROOT / "bench" / "corpus" / {case_id!r} / "fixed"
ENTRY_POINTS = {eps}
EFFECT = {effect!r}

EXPLOIT = """{exploit}
"""


def main():
    sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "src"))
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
    from exhibit_a.oracle import run_oracle
    from _harness import report

    tmp = Path(tempfile.mkdtemp(prefix="auto_finding_"))
    exploit = tmp / "test_exploit.py"
    exploit.write_text(textwrap.dedent(EXPLOIT), encoding="utf-8")
    judgement = run_oracle(FIXED_DIR, exploit, set(ENTRY_POINTS), effect=EFFECT)
    return report(Path(__file__).stem, judgement, app_is_safe=True)


if __name__ == "__main__":
    main()
'''


def run_campaign(
    targets: list[Target],
    role,
    *,
    rounds: int,
    per_round: int,
    out_dir: Path,
    run_fn: RunFn | None = None,
    timeout: float = 120.0,
) -> Report:
    """Run the full campaign; write samples, findings and counts to ``out_dir``."""
    from exhibit_a.models.errors import BudgetExceeded, SchemaValidationError

    out_dir = Path(out_dir)
    (out_dir / "tests").mkdir(parents=True, exist_ok=True)
    (out_dir / "findings").mkdir(parents=True, exist_ok=True)
    samples_path = out_dir / "samples.jsonl"
    if samples_path.exists():
        samples_path.unlink()

    run = run_fn or (lambda t, s, i: default_run_fn(t, s, i, timeout=timeout))
    report = Report()
    counts: dict[str, dict[str, int]] = {}
    for target in targets:
        for round_idx in range(rounds):
            for idx in range(per_round):
                sample_id = f"{target.case_id}-r{round_idx}s{idx}"
                if report.budget_exhausted:
                    report.skipped.append(sample_id)
                    continue
                prompt = build_prompt(target, round_idx=round_idx, sample_idx=idx)
                try:
                    result = role.run(prompt, RESPONSE_SCHEMA)
                    test_source = result.output["test"]
                    technique = result.output.get("technique", "")
                except BudgetExceeded:
                    report.budget_exhausted = True
                    report.skipped.append(sample_id)
                    continue
                except (SchemaValidationError, KeyError, TypeError, ValueError) as exc:
                    sample = _record(
                        samples_path, target, round_idx, idx, "", str(exc),
                        None, ERRORED, reason=str(exc),
                    )
                    tally(counts, sample)
                    continue
                (out_dir / "tests" / f"{sample_id}.py").write_text(test_source, encoding="utf-8")
                try:
                    judgement = run(target, test_source, sample_id)
                except Exception as exc:  # noqa: BLE001 — sandbox failures are data
                    sample = _record(
                        samples_path, target, round_idx, idx, test_source, technique,
                        None, ERRORED, reason=f"{type(exc).__name__}: {exc}",
                    )
                    tally(counts, sample)
                    continue
                try:
                    classification = classify(judgement, test_source)
                except Exception:  # noqa: BLE001 — never lose a sample to the classifier
                    classification = f"{FALSE_PROOF}:NEW" if (
                        getattr(judgement, "test_outcome", None) == "failed"
                        and getattr(judgement, "observed_effect", False)
                        and getattr(judgement, "provenance_ok", False)
                    ) else BLOCKED
                dump = judgement.model_dump() if hasattr(judgement, "model_dump") else dict(judgement)
                sample = _record(
                    samples_path, target, round_idx, idx, test_source, technique,
                    dump, classification,
                )
                tally(counts, sample)
                if classification == f"{FALSE_PROOF}:NEW":
                    name = f"auto_{target.effect}_{target.case_id}_r{round_idx}s{idx}.py"
                    (out_dir / "findings" / name).write_text(
                        _finding_source(
                            target.case_id, target.effect,
                            sorted(target.entry_points), sample,
                        ),
                        encoding="utf-8",
                    )
                    report.findings.append(name)
    report.counts = counts
    report.samples = sum(row["samples"] for row in counts.values())
    (out_dir / "counts.json").write_text(json.dumps(report.to_dict(), indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return report


def _record(samples_path: Path, target: Target, round_idx: int, idx: int,
            test_source: str, technique: str, judgement: dict[str, Any] | None,
            classification: str, *, reason: str = "") -> dict[str, Any]:
    sample = {
        "effect": target.effect,
        "case_id": target.case_id,
        "round": round_idx,
        "index": idx,
        "technique": technique,
        "test_source": test_source,
        "judgement": judgement or {"reason": reason, "test_outcome": "error",
                                   "observed_effect": False, "provenance_ok": False},
        "classification": classification,
        "recorded_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }
    with samples_path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(sample, sort_keys=True) + "\n")
    return sample


def replay_run(run_dir: Path) -> dict[str, Any]:
    """Recompute counts from a recorded run with no model call and no sandbox.

    Rebuilds each stored judgement and re-runs ``classify``; returns
    ``{"counts": ..., "match": bool, "recorded": ...}`` where ``match`` says
    whether the recomputed counts equal the recorded ``counts.json`` exactly.
    """
    from exhibit_a.oracle import Judgement

    run_dir = Path(run_dir)
    recorded = json.loads((run_dir / "counts.json").read_text(encoding="utf-8"))
    counts: dict[str, dict[str, int]] = {}
    samples = 0
    for line in (run_dir / "samples.jsonl").read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        stored = json.loads(line)
        try:
            judgement = Judgement.model_validate(stored["judgement"])
            classification = classify(judgement, stored["test_source"])
        except Exception:  # noqa: BLE001 — stored error samples carry no judgement
            classification = stored.get("classification", ERRORED)
        tally(counts, {"effect": stored["effect"], "classification": classification})
        samples += 1
    return {"counts": counts, "samples": samples, "match": counts == recorded["counts"],
            "recorded": recorded["counts"]}
